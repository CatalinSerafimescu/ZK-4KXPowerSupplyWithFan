"""Footprint for the Stonecold RAD-DY-KY/3 heatsink (3D model: gen_heatsink_step.py, FreeCAD).

Source: Stonecold RAD-DY-KY datasheet (TME) (profile 40 × 20 mm, base 4 mm, L = 30 mm,
2 PCB pins at 34 mm pitch, M3 thread for the semiconductor, 6.9 K/W) + the two photos.
Mounted upright: the 40 × 20 profile lies on the PCB, the 30 mm extrusion is the height.

Footprint origin = centre of the mounting face (the flat face with the wide fin gap and
the M3 hole). +Y points from the heatsink towards the TO-220. Values marked (est.) were
scaled from the drawing — measure the real part and adjust here, then re-run this and
gen_heatsink_step.py (FreeCAD: freecadcmd gen_heatsink_step.py) for the solid STEP model.
"""
import uuid
from pathlib import Path

PRJ = Path(__file__).resolve().parents[1]
NAME = "Heatsink_Stonecold_RAD-DY-KY-3_40x20mm_P34mm"

W = 40.0            # profile width
PLATE = 4.0         # base plate thickness, y ∈ [-PLATE, 0]
MOUNT_FIN = 7.4     # fin height on the mounting side, y ∈ [0, MOUNT_FIN]       (est.)
BACK_FIN = 20.0 - PLATE - MOUNT_FIN   # fin height on the back side (≈ 8.6)  (est.)
GAP = 19.6          # clear gap between the inner mounting-side fins           (est.)
FIN_T = 1.2         # fin thickness                                            (est.)
H = 30.0            # extrusion length = height above the PCB
PIN_X, PIN_Y = 17.0, -1.5    # PCB pins at ±17 mm (34 mm pitch), in the plate slots (y est.)
PIN_DRILL, PIN_PAD = 2.2, 3.5   # pin Ø unknown (typ. 1.5–2 mm) — measure

# fin centre-lines (x), from the drawing
FULL_FINS = [-19.4, -14.4, -10.4, 10.4, 14.4, 19.4]       # through both sides
BACK_FINS = [-7.0, -3.2, 3.2, 7.0]                         # back side only


def U():
    return str(uuid.uuid4())


def line(x0, y0, x1, y1, layer, w):
    return (f'\t(fp_line (start {x0:.3f} {y0:.3f}) (end {x1:.3f} {y1:.3f}) '
            f'(stroke (width {w}) (type solid)) (layer "{layer}") (uuid "{U()}"))')


def poly(pts, layer, w):
    xy = " ".join(f"(xy {x:.3f} {y:.3f})" for x, y in pts)
    return (f'\t(fp_poly (pts {xy}) (stroke (width {w}) (type solid)) (fill no) '
            f'(layer "{layer}") (uuid "{U()}"))')


def outline(off=0.0):
    """U-shaped outline: full profile minus the mounting-side fin gap."""
    y0, y1, g = -PLATE - BACK_FIN - off, MOUNT_FIN + off, GAP / 2 - off
    xl, xr = -W / 2 - off, W / 2 + off
    return [(xl, y0), (xr, y0), (xr, y1), (g, y1), (g, 0 - off), (-g, 0 - off), (-g, y1), (xl, y1)]


def footprint():
    fab = []
    fab.append(line(-W / 2, -PLATE, W / 2, -PLATE, "F.Fab", 0.1))
    fab.append(line(-GAP / 2, 0, GAP / 2, 0, "F.Fab", 0.1))
    for x in FULL_FINS:
        fab.append(line(x, -PLATE - BACK_FIN, x, -PLATE, "F.Fab", 0.1))
        fab.append(line(x, 0, x, MOUNT_FIN, "F.Fab", 0.1))
    for x in BACK_FINS:
        fab.append(line(x, -PLATE - BACK_FIN, x, -PLATE, "F.Fab", 0.1))
    pads = [f'\t(pad "" thru_hole circle (at {sx * PIN_X:.3f} {PIN_Y:.3f}) (size {PIN_PAD} {PIN_PAD}) '
            f'(drill {PIN_DRILL}) (layers "*.Cu" "*.Mask") (uuid "{U()}"))' for sx in (-1, 1)]
    return f'''(footprint "{NAME}"
	(version 20260206)
	(generator "pcbnew")
	(generator_version "10.0")
	(layer "F.Cu")
	(descr "Heatsink Stonecold RAD-DY-KY/3 (DY-KY, L=30 mm), TO-220/TO-3P, 40x20 mm profile, 2 PCB pins at 34 mm, M3 thread, 6.9 K/W. Origin = centre of the mounting face; TO-220 goes in the fin gap towards +Y. Generated by KiCAD/gen/gen_heatsink.py")
	(tags "heatsink TO-220 Stonecold RAD-DY-KY DY-KY")
	(property "Reference" "REF**" (at 0 {-PLATE - BACK_FIN - 1.5:.2f} 0) (layer "F.SilkS") (uuid "{U()}") (effects (font (size 1 1) (thickness 0.15))))
	(property "Value" "RAD-DY-KY/3" (at 0 -7 0) (layer "F.Fab") (uuid "{U()}") (effects (font (size 1 1) (thickness 0.15))))
	(property "Datasheet" "https://www.tme.eu/en/katalog/?search=RAD-DY-KY%2F3" (at 0 0 0) (layer "F.Fab") (hide yes) (uuid "{U()}") (effects (font (size 1 1) (thickness 0.15))))
	(property "Description" "Heatsink Stonecold RAD-DY-KY/3 40x20x30 mm, PCB pins 34 mm" (at 0 0 0) (layer "F.Fab") (hide yes) (uuid "{U()}") (effects (font (size 1 1) (thickness 0.15))))
	(attr through_hole exclude_from_pos_files)
{poly(outline(0.1), "F.SilkS", 0.12)}
{poly(outline(0.0), "F.Fab", 0.1)}
{chr(10).join(fab)}
{poly(outline(0.25), "F.CrtYd", 0.05)}
	(fp_circle (center 0 0) (end 1.6 0) (stroke (width 0.1) (type solid)) (fill no) (layer "F.Fab") (uuid "{U()}"))
{chr(10).join(pads)}
	(model "${{KIPRJMOD}}/SursaTensiune.3dshapes/RAD-DY-KY-3.step" (offset (xyz 0 0 0)) (scale (xyz 1 1 1)) (rotate (xyz 0 0 0)))
)
'''


if __name__ == "__main__":
    pretty = PRJ / "SursaTensiune.pretty"
    for old in pretty.glob("Heatsink_Stonecold_RAD-DY-KY-3_*.kicad_mod"):
        old.unlink()
    (pretty / f"{NAME}.kicad_mod").write_text(footprint(), encoding="utf-8")
    print(f"Saved: {NAME}.kicad_mod (3D: RAD-DY-KY-3.step from gen_heatsink_step.py)")
